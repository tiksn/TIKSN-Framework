using System.Collections.Immutable;
using System.Security;
using System.Text;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace TIKSN.SourceGenerators.Localization;

/// <summary>
/// Incremental source generator that generates <c>TIKSN.Localization.LocalizationKeys</c> from <c>.resx</c> files.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class LocalizationKeysGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor DuplicateLocalizationKeyRule = new(
        id: "TIKSN0001",
        title: "Duplicate localization key",
        messageFormat: "Localization key '{0}' is defined multiple times across resource files",
        category: "Localization",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Localization keys must be unique across all resource files.");

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var entriesProvider = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".resx", StringComparison.OrdinalIgnoreCase))
            .SelectMany(static (file, cancellationToken) => ExtractEntries(file, cancellationToken))
            .Collect();

        context.RegisterSourceOutput(entriesProvider, Execute);
    }

    private static void Execute(
        SourceProductionContext context,
        ImmutableArray<(string Name, string Value, string FilePath)> entries)
    {
        if (entries.IsDefaultOrEmpty)
        {
            return;
        }

        var duplicateGroups = entries
            .GroupBy(static x => x.Name, StringComparer.OrdinalIgnoreCase)
            .Where(static g => g.Count() > 1)
            .ToArray();

        if (duplicateGroups.Length > 0)
        {
            foreach (var group in duplicateGroups)
            {
                foreach (var (_, _, filePath) in group)
                {
                    var location = Location.Create(
                        filePath,
                        new TextSpan(0, 0),
                        new LinePositionSpan(LinePosition.Zero, LinePosition.Zero));

                    context.ReportDiagnostic(Diagnostic.Create(
                        DuplicateLocalizationKeyRule,
                        location,
                        group.Key));
                }
            }

            return;
        }

        var sortedEntries = entries
            .OrderBy(static x => x.Name, StringComparer.OrdinalIgnoreCase)
            .ToArray();

        var sb = new StringBuilder();
        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("#nullable enable");
        _ = sb.AppendLine();
        _ = sb.AppendLine("namespace TIKSN.Localization;");
        _ = sb.AppendLine();
        _ = sb.AppendLine("/// <summary>");
        _ = sb.AppendLine("/// Keys to known localization resources");
        _ = sb.AppendLine("/// </summary>");
        _ = sb.AppendLine("public static partial class LocalizationKeys");
        _ = sb.AppendLine("{");

        for (var i = 0; i < sortedEntries.Length; i++)
        {
            if (i > 0)
            {
                _ = sb.AppendLine();
            }

            var (Name, Value, _) = sortedEntries[i];
            _ = sb.AppendLine("    /// <summary>");
            _ = sb.Append("    /// Key: ").AppendLine(Name);
            _ = sb.Append("    /// Original Value: ").AppendLine(Value);
            _ = sb.AppendLine("    /// </summary>");
            _ = sb.Append("    public static string Key")
                .Append(Name)
                .Append(" => \"")
                .Append(Name)
                .AppendLine("\";");
        }

        _ = sb.AppendLine("}");

        context.AddSource("LocalizationKeys.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static ImmutableArray<(string Name, string Value, string FilePath)> ExtractEntries(
        AdditionalText additionalText,
        CancellationToken cancellationToken)
    {
        var sourceText = additionalText.GetText(cancellationToken);
        if (sourceText is null)
        {
            return [];
        }

        var document = XDocument.Parse(sourceText.ToString());
        var rootElement = document.Element("root");
        if (rootElement is null)
        {
            return [];
        }

        var builder = ImmutableArray.CreateBuilder<(string Name, string Value, string FilePath)>();

        foreach (var dataElement in rootElement.Elements("data"))
        {
            var name = dataElement.Attribute("name")?.Value;
            var value = dataElement.Element("value")?.Value;

            if (!string.IsNullOrEmpty(name) && value is not null)
            {
                var escapedValue = SecurityElement.Escape(value)?.Trim() ?? string.Empty;
                builder.Add((name!, escapedValue, additionalText.Path));
            }
        }

        return builder.ToImmutable();
    }
}
